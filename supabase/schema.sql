CREATE POLICY "Allow public all on staff_logs" ON staff_logs FOR ALL USING (true);
CREATE POLICY "Allow public all on products" ON products FOR ALL USING (true);
CREATE POLICY "Allow public all on invoices" ON invoices FOR ALL USING (true);
CREATE POLICY "Allow public all on invoice_items" ON invoice_items FOR ALL USING (true);
CREATE POLICY "Allow public all on purchases" ON purchases FOR ALL USING (true);
CREATE POLICY "Allow public all on purchase_items" ON purchase_items FOR ALL USING (true);
CREATE POLICY "Allow public all on inventory_history" ON inventory_history FOR ALL USING (true);

